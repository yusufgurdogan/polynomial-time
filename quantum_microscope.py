def analyze_quantum_samples(info, elements):
    """Deep analysis of the quantum samples (elements of L*/Z^d)."""

    N = info['N']
    p = info['p']
    q = info['q']
    d = info['d']
    bases = info['bases']
    genus = info['genus']
    dlp = info['dlp']
    dlq = info['dlq']
    snf = info['snf']

    n_elements = len(elements)

    print(f"\n  N = {N} = {p} × {q}  ({N.bit_length()} bits)")
    print(f"  Factor base: {bases}  (d = {d})")
    print(f"  L_R rank: {info['rank']}")
    print(f"  SNF diagonal: {snf}")
    print(f"  |L*/Z^d| = {n_elements}")
    print(f"  Genus character ε: {genus}")

    # ---- STRUCTURE OF THE GROUP ----
    print(f"\n  --- Group structure ---")
    nonzero_snf = [s for s in snf if s > 0]
    group_str = " × ".join(f"Z/{s}" for s in nonzero_snf)
    print(f"  L*/Z^d ≅ {group_str}")

    # ---- COORDINATE ANALYSIS ----
    print(f"\n  --- Coordinate analysis ---")
    print(f"  Each element is a point in [0,1)^{d} (the d-torus)")

    # What values does each coordinate take?
    for i in range(d):
        vals = sorted(set(round(float(e), 10) for e in elements[:, i]))
        n_distinct = len(vals)
        print(f"  coord {i} (base {bases[i]}): {n_distinct} distinct values", end="")
        if n_distinct <= 20:
            # Show the actual values as fractions
            fracs = []
            for v in vals:
                # Try to express as a/b
                best_frac = None
                for denom in range(1, max(snf) + 1 if snf else 2):
                    numer = round(v * denom)
                    if abs(v - numer/denom) < 1e-6:
                        best_frac = f"{numer}/{denom}" if numer != 0 else "0"
                        break
                fracs.append(best_frac if best_frac else f"{v:.4f}")
            print(f"  values: {fracs}")
        else:
            print(f"  (range: [{min(vals):.4f}, {max(vals):.4f}])")

    # ---- RELATIONSHIP TO p AND q ----
    print(f"\n  --- Relationship to p, q ---")

    # Key question: do the coordinates encode information about p?
    # The dual lattice L* is determined by L_R, which depends on the discrete logs.
    # The discrete logs mod p encode the Legendre symbols (b_i/p).
    # So L*/Z^d encodes (b_i/p) for all bases — which IS the factoring secret.

    # But HOW is it encoded? Let's see.
    # L_R is defined by: Σ e_i · dlog_p(b_i) ≡ 0 (mod p-1) AND Σ e_i · dlog_q(b_i) ≡ 0 (mod q-1)
    # So L_R depends on the discrete logs mod p and mod q.
    # L* depends on L_R.
    # The elements of L*/Z^d are the cosets.

    # Can we recover the discrete logs from the elements of L*/Z^d?
    # The elements w ∈ L*/Z^d satisfy: <w, e> ∈ Z for all e ∈ L_R.
    # Equivalently: B_LR @ w ∈ Z^rank.

    # The coordinates of w are related to the inverse of B_LR.

    # Let's check: for each element, compute B_LR @ w mod 1
    B_LR = info['B_LR'].astype(np.float64)
    for i, w in enumerate(elements[:5]):
        prod = B_LR @ w
        prod_frac = prod - np.round(prod)
        print(f"  w[{i}] = {np.round(w, 4)}  →  B_LR @ w mod 1 = {np.round(prod_frac, 6)}")

    # ---- THE DEEP QUESTION ----
    print(f"\n  --- The deep question ---")
    print(f"  L*/Z^d is determined by L_R, which is determined by (p, q).")
    print(f"  The quantum circuit samples UNIFORMLY from L*/Z^d.")
    print(f"  Can ANYTHING about L*/Z^d be computed from N alone?")

    # Test 1: Can we compute |L*/Z^d| from N?
    # |L*/Z^d| = det(L_R) = product of SNF diagonal entries
    det_LR = 1
    for s in snf:
        if s > 0:
            det_LR *= s
    print(f"\n  Test 1: |L*/Z^d| = det(L_R) = {det_LR}")
    print(f"    (p-1)(q-1) = {(p-1)*(q-1)}")
    print(f"    lcm(p-1,q-1) = {(p-1)*(q-1)//math.gcd(p-1,q-1)}")
    print(f"    Relation: det(L_R) is related to the structure of (Z/NZ)*")

    # Test 2: The coordinates of L*/Z^d elements as rational numbers
    # What denominators appear?
    print(f"\n  Test 2: Denominators in L*/Z^d coordinates")
    all_denoms = set()
    for w in elements:
        for v in w:
            # Find smallest denominator
            for denom in range(1, 10000):
                if abs(v * denom - round(v * denom)) < 1e-6:
                    all_denoms.add(denom)
                    break
    print(f"    Denominators that appear: {sorted(all_denoms)[:20]}")
    print(f"    These should divide the SNF entries: {nonzero_snf}")

    # Test 3: Projection onto genus direction
    print(f"\n  Test 3: Genus structure of L*/Z^d")
    genus_vec = np.array(genus, dtype=np.float64)
    if np.linalg.norm(genus_vec) > 0:
        projections = elements @ genus_vec
        proj_mod1 = projections % 1.0
        proj_values = sorted(set(round(float(v), 8) for v in proj_mod1))
        print(f"    Projection of L*/Z^d onto genus direction ε:")
        if len(proj_values) <= 30:
            for v in proj_values:
                count = sum(1 for pv in proj_mod1 if abs(pv - v) < 1e-6)
                # Express as fraction
                for denom in range(1, max(snf) + 1 if snf else 2):
                    numer = round(v * denom)
                    if abs(v - numer/denom) < 1e-6:
                        frac = f"{numer}/{denom}"
                        break
                else:
                    frac = f"{v:.6f}"
                print(f"      {frac}: {count} elements")
        print(f"    The genus character splits L*/Z^d into even/odd halves.")
        print(f"    Only genus-ODD samples lead to factoring.")
        print(f"    But which half is which requires knowing ε = ((b_i/p)+1)/2,")
        print(f"    which requires knowing p.")

    # Test 4: What do the elements look like modulo small integers?
    print(f"\n  Test 4: Elements mod small integers")
    for m in [2, 3, 4, 6]:
        coords_mod_m = np.round(elements * m) % m
        unique_patterns = set(tuple(int(x) for x in row) for row in coords_mod_m)
        print(f"    mod {m}: {len(unique_patterns)} distinct patterns out of {m**d} possible")

    # Test 5: Are some coordinates predictable from N alone?
    # The Jacobi symbol (b_i/N) is computable without knowing p.
    # It equals (b_i/p)(b_i/q). If (b_i/N) = -1, we know (b_i/p) ≠ (b_i/q).
    # If (b_i/N) = 1, we know (b_i/p) = (b_i/q) but not which.
    print(f"\n  Test 5: Jacobi symbols (computable from N)")
    for i, b in enumerate(bases):
        j_symbol = jacobi_sym(b, N)
        leg_p = 1 if dlp[i] % 2 == 0 else -1
        leg_q = 1 if dlq[i] % 2 == 0 else -1
        print(f"    ({b}/N) = {j_symbol:+d}  "
              f"({b}/p) = {leg_p:+d}  ({b}/q) = {leg_q:+d}  "
              f"ε_{i} = {genus[i]}")

    # Test 6: The SPACING between elements
    print(f"\n  Test 6: Spacing between consecutive elements (1D projection)")
    if n_elements > 1 and n_elements < 10000:
        # Project onto first coordinate
        coord0 = sorted(elements[:, 0] % 1.0)
        spacings = [coord0[i+1] - coord0[i] for i in range(len(coord0)-1)]
        if spacings:
            mean_sp = np.mean(spacings)
            std_sp = np.std(spacings)
            print(f"    Mean spacing: {mean_sp:.6f} (expected 1/{n_elements} = {1/n_elements:.6f})")
            print(f"    Std of spacing: {std_sp:.6f}")
            print(f"    Min spacing: {min(spacings):.6f}")
            print(f"    Max spacing: {max(spacings):.6f}")
            print(f"    Spacing ratio (max/min): {max(spacings)/min(spacings):.2f}" if min(spacings) > 0 else "")

    # Test 7: Reconstruct L_R from L*/Z^d (this is what LLL does)
    print(f"\n  Test 7: Can we reconstruct L_R from L*/Z^d?")
    print(f"    Given {n_elements} elements of L*/Z^d, LLL on the dual")
    print(f"    recovers L_R. This is exactly Regev's classical post-processing.")
    print(f"    The quantum advantage is PRODUCING the {n_elements} elements.")

    return elements


def jacobi_sym(a, n):
    if n <= 0 or n % 2 == 0: return 0
    a = a % n
    result = 1
    while a != 0:
        while a % 2 == 0:
            a //= 2
            if n % 8 in (3, 5): result = -result
        a, n = n, a
        if a % 4 == 3 and n % 4 == 3: result = -result
        a = a % n
    return result if n == 1 else 0


