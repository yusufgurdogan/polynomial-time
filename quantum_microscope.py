def compare_classical_to_quantum(info, quantum_elements):
    """
    For each classical sampling strategy, see how close its output
    is to the actual quantum samples (elements of L*/Z^d).
    """
    N = info['N']
    d = info['d']
    bases = info['bases']

    print(f"\n  --- Classical vs Quantum comparison ---")

    B_LR = info['B_LR'].astype(np.float64)

    # The "correct" samples are the quantum_elements.
    # A classical strategy produces vectors w ∈ [0,1)^d.
    # We measure: min distance from each classical sample to any quantum element.

    n_samples = min(1000, len(quantum_elements) * 10)

    strategies = {}

    # Strategy: Uniform random (baseline)
    uniform = np.random.rand(n_samples, d)
    strategies['uniform'] = uniform

    # Strategy: Use Jacobi symbols to guess
    # (b_i/N) tells us if (b_i/p) = (b_i/q).
    # If (b_i/N) = 1 and b_i is small, likely QR mod both.
    # Use this to guess genus character → guess coordinates.
    jacobi_guesses = np.random.rand(n_samples, d)
    for i, b in enumerate(bases):
        j = jacobi_sym(b, N)
        if j == 1:
            # Guess: b is QR mod both p and q, so genus[i] = 0
            # This constrains the i-th coordinate of L*/Z^d elements
            pass  # Hard to translate genus into coordinate values without more info
    strategies['jacobi_guess'] = jacobi_guesses

    # Strategy: Random lattice-structured points
    # Generate random integer vectors, project via (B_LR^{-T})
    # This produces points in L* but not necessarily in L*/Z^d
    if info['rank'] > 0:
        # Random integer vectors of length rank
        rand_ints = np.random.randint(-10, 11, size=(n_samples, info['rank']))
        # Project: each row r gives w = V @ (r_1/s_1, ..., r_r/s_r, 0, ..., 0)
        # But we don't know the SNF from N alone!
        pass

    # Strategy: Evaluate specific functions of N at the base primes
    # For each base b_i, compute b_i^{(N-1)/2} mod N (Euler criterion)
    euler_vals = []
    for b in bases:
        e = pow(b, (N - 1) // 2, N)
        euler_vals.append(e / N)  # Normalize to [0, 1)
    euler_samples = np.tile(euler_vals, (n_samples, 1))
    euler_samples += np.random.randn(n_samples, d) * 0.01  # Small noise
    euler_samples = euler_samples % 1.0
    strategies['euler'] = euler_samples

    # Strategy: Power residues — b_i^k mod N for various k
    power_samples = np.zeros((n_samples, d))
    for s in range(n_samples):
        k = random.randint(1, N)
        for i, b in enumerate(bases):
            power_samples[s, i] = pow(b, k, N) / N
    strategies['power_residue'] = power_samples

    # Measure quality: for each strategy, what fraction of samples
    # land close to a quantum element?
    print(f"  Quality metric: fraction of classical samples within δ of a quantum element")
    print(f"  (δ thresholds: 0.01, 0.05, 0.10)")

    for name, samples in strategies.items():
        # For each classical sample, find distance to nearest quantum element
        min_dists = []
        for s in samples[:200]:  # Limit for speed
            # Distance on torus
            diffs = quantum_elements - s[np.newaxis, :]
            diffs = diffs - np.round(diffs)  # Wrap to [-0.5, 0.5)
            dists = np.sqrt(np.sum(diffs**2, axis=1))
            min_dists.append(np.min(dists))

        mean_dist = np.mean(min_dists)
        frac_01 = np.mean(np.array(min_dists) < 0.01)
        frac_05 = np.mean(np.array(min_dists) < 0.05)
        frac_10 = np.mean(np.array(min_dists) < 0.10)

        print(f"    {name:20s}: mean_dist={mean_dist:.4f}  "
              f"<0.01:{frac_01:.1%}  <0.05:{frac_05:.1%}  <0.10:{frac_10:.1%}")

    # Expected for uniform: if there are K quantum elements in [0,1)^d,
    # a random point is within δ of one of them with prob ≈ K · V_d(δ)
    # where V_d(δ) is the volume of a d-ball of radius δ.
    n_q = len(quantum_elements)
    print(f"\n  Expected for uniform random (K={n_q} elements in [0,1)^{d}):")
    for delta in [0.01, 0.05, 0.10]:
        # Volume of d-ball
        V_d = (math.pi ** (d/2)) / math.gamma(d/2 + 1) * delta**d
        expected = min(1.0, n_q * V_d)
        print(f"    <{delta}: {expected:.4%}")


