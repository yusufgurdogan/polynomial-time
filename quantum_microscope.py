def enumerate_dual_quotient(info):
    """
    Enumerate all elements of L*/Z^d (the group the quantum circuit samples from).

    Using Smith Normal Form: if B_LR has SNF diag (s_1, ..., s_r), then
    L*/Z^d ≅ Z/s_1 x ... x Z/s_r

    The elements in the original coordinates are:
    v_k = V @ (k_1/s_1, ..., k_r/s_r, 0, ..., 0)^T  mod Z^d
    for k_i = 0, ..., s_i - 1
    """
    snf = info['snf']
    V = info['V']
    d = info['d']
    rank = info['rank']

    # Filter out zero diagonal entries
    nonzero_snf = [(i, s) for i, s in enumerate(snf) if s > 0]

    if not nonzero_snf:
        return np.array([[0.0] * d])

    # Total number of elements
    total = 1
    for _, s in nonzero_snf:
        total *= s

    if total > 100000:
        print(f"  WARNING: L*/Z^d has {total} elements, sampling instead of enumerating")
        # Sample uniformly
        elements = []
        for _ in range(min(10000, total)):
            coords = np.zeros(d, dtype=np.float64)
            for idx, s in nonzero_snf:
                k = random.randint(0, s - 1)
                coords += (k / s) * V[:, idx].astype(np.float64)
            coords = coords % 1.0
            elements.append(coords)
        return np.array(elements)

    # Enumerate all elements
    ranges = [range(s) for _, s in nonzero_snf]
    elements = []

    for combo in iproduct(*ranges):
        coords = np.zeros(d, dtype=np.float64)
        for (idx, s), k in zip(nonzero_snf, combo):
            coords += (k / s) * V[:, idx].astype(np.float64)
        coords = coords % 1.0
        # Shift to [-0.5, 0.5)
        coords = coords - np.floor(coords + 0.5)
        coords = coords % 1.0  # back to [0, 1)
        elements.append(coords)

    return np.array(elements)


