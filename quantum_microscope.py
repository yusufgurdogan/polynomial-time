def build_lattices(N, p, q, d=None):
    """
    Build L_R and L* for N = pq with d-dimensional factor base.

    L_R = {e ∈ Z^d : ∏ b_i^{e_i} ≡ 1 mod N}
    L* = dual lattice = {w ∈ R^d : <w, e> ∈ Z for all e ∈ L_R}
    L*/Z^d = finite group of order det(L_R)

    Returns: bases list, L_R basis, L* basis, elements of L*/Z^d
    """
    primes = [pr for pr in small_primes(200) if N % pr != 0]
    if d is None:
        d = min(len(primes), 8)
    bases = primes[:d]

    # Compute discrete logs
    g_p = primitive_root(p)
    g_q = primitive_root(q)
    dlp = [discrete_log(b % p, g_p, p) for b in bases]
    dlq = [discrete_log(b % q, g_q, q) for b in bases]

    # Genus character
    genus = [dl % 2 for dl in dlp]

    # Build L_R via augmented lattice + LLL
    from fpylll import IntegerMatrix, LLL

    dim = d + 2
    B = IntegerMatrix(dim, dim)
    for i in range(d):
        B[i, i] = 1
        B[i, d] = dlp[i]
        B[i, d + 1] = dlq[i]
    B[d, d] = p - 1
    B[d + 1, d + 1] = q - 1

    LLL.reduction(B)

    # Extract kernel vectors (auxiliary coords = 0)
    kernel_vecs = []
    for i in range(dim):
        v = np.array([int(B[i, j]) for j in range(d)])
        aux = [int(B[i, j]) for j in range(d, dim)]
        if all(a == 0 for a in aux) and np.any(v != 0):
            kernel_vecs.append(v)

    if len(kernel_vecs) == 0:
        return None

    # L_R basis matrix (rows = basis vectors)
    B_LR = np.array(kernel_vecs, dtype=np.float64)
    rank = B_LR.shape[0]

    # Compute L* basis: if B_LR is rank x d, then L* has a basis
    # L* = {w : B_LR @ w ∈ Z^rank}
    # A basis for L* (as a d-dimensional lattice containing Z^d):
    # L* is generated by Z^d plus vectors that map to the dual of B_LR

    # For L*/Z^d: this is isomorphic to Z^rank / (B_LR^T @ Z^d ∩ Z^rank)
    # More precisely: L*/Z^d ≅ Z^d / L_R
    # Wait, that's not right either. Let me think carefully.

    # L_R is a sublattice of Z^d. The dual lattice L* contains Z^d.
    # L*/Z^d is a finite group of order det(L_R) (when L_R has full rank in some sense).

    # Actually, for the quotient group that Regev samples from:
    # The quantum circuit samples from the cosets of Z^d in L*.
    # |L*/Z^d| = |Z^d/L_R| = det(L_R) (the index of L_R in Z^d).

    # But L_R has rank < d typically. So the quotient is infinite in some directions.
    # Regev's algorithm works in the quotient R^d/Z^d (the d-torus),
    # and L*/Z^d is a finite subset of this torus when projected to the
    # subspace spanned by L_R.

    # Let me compute this more carefully.
    # L_R has rank r and lives in Z^d.
    # L* = {w ∈ R^d : <w, x> ∈ Z for all x ∈ L_R}
    # Since L_R ⊂ Z^d, we have Z^d ⊂ L* (because <z, x> ∈ Z for z ∈ Z^d, x ∈ Z^d).
    # L*/Z^d is a finite group of order det(Smith normal form of B_LR) when rank = r.

    # To enumerate L*/Z^d:
    # Let B_LR be the r x d integer matrix of L_R basis vectors.
    # Compute Smith Normal Form: U @ B_LR @ V = S where S is diagonal.
    # Then L*/Z^d ≅ Z/s_1 x Z/s_2 x ... x Z/s_r (s_i are diagonal entries of S).
    # The elements can be enumerated as (k_1/s_1, ..., k_r/s_r) in appropriate coordinates.

    # Use numpy for SNF (approximate, then round)
    # Actually, let's use a direct approach: find the quotient group.

    # The Smith Normal Form of an integer matrix:
    B_int = np.array(kernel_vecs, dtype=np.int64)

    # Simple SNF for small matrices
    snf_diag, U, V = smith_normal_form(B_int)

    return {
        'bases': bases,
        'd': d,
        'rank': rank,
        'B_LR': B_int,
        'kernel_vecs': kernel_vecs,
        'genus': genus,
        'dlp': dlp,
        'dlq': dlq,
        'snf': snf_diag,
        'U': U,
        'V': V,
        'p': p,
        'q': q,
        'N': N,
    }


def smith_normal_form(M):
    """
    Compute the Smith Normal Form of integer matrix M.
    Returns (diagonal, U, V) where U @ M @ V = diag(diagonal).
    """
    M = np.array(M, dtype=np.int64).copy()
    r, c = M.shape
    U = np.eye(r, dtype=np.int64)
    V = np.eye(c, dtype=np.int64)

    for k in range(min(r, c)):
        # Find pivot
        found = False
        for i in range(k, r):
            for j in range(k, c):
                if M[i, j] != 0:
                    # Swap rows k, i
                    if i != k:
                        M[[k, i]] = M[[i, k]]
                        U[[k, i]] = U[[i, k]]
                    # Swap cols k, j
                    if j != k:
                        M[:, [k, j]] = M[:, [j, k]]
                        V[:, [k, j]] = V[:, [j, k]]
                    found = True
                    break
            if found:
                break
        if not found:
            break

        # Reduce using the pivot
        changed = True
        while changed:
            changed = False
            # Row operations
            for i in range(k + 1, r):
                if M[i, k] != 0:
                    q = M[i, k] // M[k, k]
                    M[i] -= q * M[k]
                    U[i] -= q * U[k]
                    if M[i, k] != 0:
                        # Need to use extended gcd
                        g, s, t = extended_gcd(int(M[k, k]), int(M[i, k]))
                        a, b = int(M[k, k]) // g, int(M[i, k]) // g
                        new_k = s * M[k] + t * M[i]
                        new_i = -b * M[k] + a * M[i]
                        M[k] = new_k
                        M[i] = new_i
                        new_uk = s * U[k] + t * U[i]
                        new_ui = -b * U[k] + a * U[i]
                        U[k] = new_uk
                        U[i] = new_ui
                        changed = True
            # Column operations
            for j in range(k + 1, c):
                if M[k, j] != 0:
                    q = M[k, j] // M[k, k]
                    M[:, j] -= q * M[:, k]
                    V[:, j] -= q * V[:, k]
                    if M[k, j] != 0:
                        g, s, t = extended_gcd(int(M[k, k]), int(M[k, j]))
                        a, b = int(M[k, k]) // g, int(M[k, j]) // g
                        new_k = s * M[:, k] + t * M[:, j]
                        new_j = -b * M[:, k] + a * M[:, j]
                        M[:, k] = new_k
                        M[:, j] = new_j
                        new_vk = s * V[:, k] + t * V[:, j]
                        new_vj = -b * V[:, k] + a * V[:, j]
                        V[:, k] = new_vk
                        V[:, j] = new_vj
                        changed = True

    # Make diagonal positive
    diag = []
    for k in range(min(r, c)):
        if M[k, k] < 0:
            M[k] = -M[k]
            U[k] = -U[k]
        diag.append(int(M[k, k]))

    return diag, U, V


def extended_gcd(a, b):
    if b == 0:
        return a, 1, 0
    g, s, t = extended_gcd(b, a % b)
    return g, t, s - (a // b) * t


