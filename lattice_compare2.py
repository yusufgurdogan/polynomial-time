def compare(N, p, q, num_primes=6):
    print(f"\n{'='*70}")
    print(f"  N = {N} = {p} × {q} ({N.bit_length()} bits)")
    print(f"{'='*70}")

    bases = [pr for pr in small_primes(50) if N % pr != 0][:num_primes]
    d = len(bases)
    print(f"  Bases: {bases}")

    # Build Regev lattice
    kernel_R, dlogs_p, dlogs_q = build_regev_lattice_proper(N, p, q, bases)
    print(f"\n  L_R (Regev): {len(kernel_R)} kernel vectors found")
    for v in kernel_R[:8]:
        norm = math.sqrt(sum(x*x for x in v))
        # Verify: ∏ bases[i]^v[i] ≡ 1 mod N
        prod = 1
        for i, e in enumerate(v):
            if e >= 0:
                prod = (prod * pow(bases[i], e, N)) % N
            else:
                prod = (prod * pow(bases[i], -e, N)) % N
                prod = pow(prod, -1, N) if math.gcd(prod, N) == 1 else 0
        # Simpler verification using dlogs
        check_p = sum(v[i] * dlogs_p[i] for i in range(d)) % (p - 1)
        check_q = sum(v[i] * dlogs_q[i] for i in range(d)) % (q - 1)
        ok = "✓" if (check_p == 0 and check_q == 0) else "✗"
        print(f"    {v}  norm={norm:.2f}  {ok}")

    # Build class group genus constraint
    genus = build_class_lattice_proper(N, p, q, bases)
    print(f"\n  Genus characters (ℓ/p): {genre_str(bases, genus)}")

    # L_C = L_R ∩ {e : Σ eᵢ genus[i] ≡ 0 mod 2}
    kernel_C = [v for v in kernel_R if sum(v[i] * genus[i] for i in range(d)) % 2 == 0]
    kernel_C_complement = [v for v in kernel_R if sum(v[i] * genus[i] for i in range(d)) % 2 == 1]

    print(f"\n  L_C (Class group): {len(kernel_C)} vectors (genus-even)")
    for v in kernel_C[:5]:
        norm = math.sqrt(sum(x*x for x in v))
        print(f"    {v}  norm={norm:.2f}")

    print(f"\n  L_R \\ L_C: {len(kernel_C_complement)} vectors (genus-odd)")
    for v in kernel_C_complement[:5]:
        norm = math.sqrt(sum(x*x for x in v))
        print(f"    {v}  norm={norm:.2f}")

    # THE KEY STRUCTURAL INSIGHT:
    # L_R has index 2 in L_C (genus is a mod-2 constraint)
    # So L_C ⊂ L_R with [L_R : L_C] = 2
    # Actually it's the OTHER way: L_C ⊂ L_R
    # L_C = {e ∈ L_R : genus parity = 0}

    print(f"\n  STRUCTURAL RESULT:")
    print(f"  L_C = L_R ∩ (genus hyperplane)")
    print(f"  [L_R : L_C] = 2 (genus theory: 2 genera for N=pq)")
    print(f"  L_R \\ L_C contains vectors where ∏ bᵢ^eᵢ ≡ 1 mod N")
    print(f"  but the product is a QNR mod p (and QR mod q, or vice versa).")

    # Factor revelation via genus-odd vectors
    print(f"\n  --- Factor revelation test ---")
    for v in kernel_R:
        # For each relation, try the gcd trick
        # Compute x = ∏ bases[i]^(v[i]/2) if all even
        if all(e % 2 == 0 for e in v) and any(e != 0 for e in v):
            half = 1
            for i, e in enumerate(v):
                if e > 0:
                    half = (half * pow(bases[i], e // 2, N)) % N
                elif e < 0:
                    inv = pow(bases[i], -e // 2, N)
                    half = (half * pow(inv, -1, N)) % N if math.gcd(inv, N) == 1 else 0
            g1 = math.gcd(half - 1, N)
            g2 = math.gcd(half + 1, N)
            genus_val = sum(v[i] * genus[i] for i in range(d)) % 2
            tag = "genus-even (L_C)" if genus_val == 0 else "GENUS-ODD (L_R\\L_C)"
            if 1 < g1 < N or 1 < g2 < N:
                factor = g1 if 1 < g1 < N else g2
                print(f"    {v} → FACTOR {factor}!  [{tag}]")
            else:
                print(f"    {v} → no factor  [{tag}]")

    # The deep question: genus-odd vectors in L_R should reveal factors
    # because they correspond to x with x ≡ QR mod p, x ≡ QNR mod q
    # So x^((p-1)/2) ≡ 1 mod p but x^((q-1)/2) ≡ -1 mod q
    # Meaning gcd(x^((N-1)/2) ± 1, N) might factor!
    print(f"\n  --- Genus-odd Euler criterion test ---")
    for v in kernel_C_complement[:5]:
        # Compute x = ∏ bases[i]^v[i] mod N (this should be 1 by construction)
        # But the HALF-product ∏ bases[i]^(v[i]) is in L_R, meaning it's ≡ 1 mod N
        # The genus-odd property means the "path" to 1 goes through different
        # quadratic residuosity mod p vs q
        # Can we exploit this without computing the half-product?

        # Try: compute ∏ bases[i]^|v[i]| mod p and mod q separately
        # This requires knowing p, q — but the POINT is to see if the
        # lattice structure itself encodes the difference
        prod_mod_p = 1
        prod_mod_q = 1
        for i, e in enumerate(v):
            prod_mod_p = (prod_mod_p * pow(bases[i] % p, e % (p-1), p)) % p
            prod_mod_q = (prod_mod_q * pow(bases[i] % q, e % (q-1), q)) % q
        print(f"    {v}: mod p={prod_mod_p}, mod q={prod_mod_q}")


def genre_str(bases, genus):
    return ", ".join(f"({b}/p)={'QR' if g==0 else 'QNR'}" for b, g in zip(bases, genus))


def _primitive_root(p):
    """Find a primitive root mod prime p."""
    if p == 2:
        return 1
    phi = p - 1
    factors = _factorize_small(phi)
    for g in range(2, p):
        if all(pow(g, phi // f, p) != 1 for f in factors):
            return g
    return None


def _discrete_log(a, g, p):
    """Compute log_g(a) mod (p-1) by brute force."""
    a = a % p
    if a == 0:
        return 0
    current = 1
    for k in range(p):
        if current == a:
            return k
        current = (current * g) % p
    return 0


def _factorize_small(n):
    """Return set of prime factors of n."""
    factors = set()
    d = 2
    while d * d <= n:
        while n % d == 0:
            factors.add(d)
            n //= d
        d += 1
    if n > 1:
        factors.add(n)
    return factors


