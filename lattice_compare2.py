#!/usr/bin/env python3
"""
Lattice comparison v2 — proper construction.

For small N = pq, build:
  L_R: kernel of the map Z^d → (Z/NZ)*, (e₁,...,e_d) ↦ ∏ bᵢ^eᵢ mod N
  L_C: kernel of the map Z^d → Cl(Q(√N)), (e₁,...,e_d) ↦ ∏ [𝔭ᵢ]^eᵢ

These are properly lattices. We build them by finding a basis for each kernel.
"""

import math
import sys
import numpy as np
from fpylll import IntegerMatrix, LLL

sys.stdout.reconfigure(line_buffering=True)


def small_primes(limit):
    s = [True] * (limit + 1)
    s[0] = s[1] = False
    for i in range(2, int(limit**0.5) + 1):
        if s[i]:
            for j in range(i*i, limit + 1, i):
                s[j] = False
    return [i for i in range(limit + 1) if s[i]]


